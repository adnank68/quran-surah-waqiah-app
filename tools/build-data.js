// نسخه‌ی عثمانی، «بسم الله» را به آیه‌ی اول چسبانده. شکل نوشتاری‌اش در مصحف
// عثمانی الف وصل و الف خنجری دارد، پس به‌جای مقایسه‌ی رشته‌ی خام، بر اساس
// حروف پایه (بدون اعراب) جدا می‌کنیم تا به شکل دقیق علامت‌ها وابسته نباشد.
const DIACRITICS = /[ؐ-ًؚ-ٰٟۖ-ۭـ]/g;
const ALEF_FORMS = /[آأإٱ]/g; // آ أ إ ٱ → ا

function baseLetters(s) {
  return s.replace(DIACRITICS, '').replace(ALEF_FORMS, 'ا').replace(/\s+/g, '');
}

function splitBismillah(ayah1) {
  const target = baseLetters('بسم الله الرحمن الرحيم');
  let acc = '';
  for (let i = 0; i < ayah1.length; i++) {
    acc += ayah1[i];
    if (baseLetters(acc) === target) {
      // اعرابِ چسبیده به آخرین حرف، بعد از تطبیقِ حروف پایه می‌آید؛ آن را هم بردار
      let j = i + 1;
      while (j < ayah1.length && /[ؐ-ًؚ-ٰٟۖ-ۭ]/.test(ayah1[j])) j++;
      return { bismillah: ayah1.slice(0, j).trim(), rest: ayah1.slice(j).trim() };
    }
  }
  return null;
}

